/**
 * Regenerates `src/pdf/generated/embeddedFontData.ts` from the TTFs in
 * `src/pdf/fonts/`. Run `node scripts/generate-font-module.mjs` after adding or
 * replacing a font. The module is committed, so this only needs to run again
 * when the font set changes.
 *
 * The bytes ship inside a generated JavaScript module rather than behind a
 * runtime URL because the app's content security policy forbids fetches; see
 * the R09 readiness work. The export path (pdf-lib in the worker) and the
 * preview (FontFace in the main thread) both read from this module, which is
 * what keeps their typography identical.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const fontsDir = resolve('src/pdf/fonts');
const outFile = resolve('src/pdf/generated/embeddedFontData.ts');

const entries = readdirSync(fontsDir)
  .filter((name) => name.endsWith('.ttf'))
  .sort()
  .map((name) => {
    const bytes = readFileSync(join(fontsDir, name));
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    return { name, base64: bytes.toString('base64'), sha256 };
  });

if (entries.length === 0) {
  throw new Error(`No .ttf files found in ${fontsDir}`);
}

const body = `/**
 * GENERATED by scripts/generate-font-module.mjs from src/pdf/fonts/. Do not
 * edit; regenerate instead.
 */

export type EmbeddedFont = {
  /** File name of the source TTF, for the license manifest. */
  fileName: string;
  base64: string;
  sha256: string;
};

export const EMBEDDED_FONTS: EmbeddedFont[] = [
${entries.map((font) => `  { fileName: ${JSON.stringify(font.name)}, base64: '${font.base64}', sha256: '${font.sha256}' }`).join(',\n')}
];

export const EMBEDDED_PRIMARY_FONT = EMBEDDED_FONTS[0]!;
`;

writeFileSync(outFile, body);

for (const font of entries) {
  console.log(`${font.name}: ${font.base64.length} base64 chars, sha256 ${font.sha256.slice(0, 12)}…`);
}
console.log(`Wrote ${outFile}`);
