/**
 * Regenerates `src/pdf/generated/pdfAssets.ts` from pdf.js's CMap and standard
 * font data. Run `node scripts/generate-asset-module.mjs` after updating
 * pdfjs-dist. The module is committed, so this only reruns on a pdf.js update.
 *
 * The bytes ship inside a generated JavaScript module rather than behind URLs
 * because the content security policy forbids fetches (`connect-src 'none'`):
 * pdf.js's default factories would fetch /cmaps/ and /standard_fonts/ at
 * render time and fail. Custom factories in src/pdf/runtime.ts read this
 * module instead, so a CJK-encoded or standard-font PDF renders with zero
 * network activity.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, resolve } from 'node:path';

const pdfjsDir = resolve('node_modules/pdfjs-dist');

function collect(dirName) {
  const dir = join(pdfjsDir, dirName);
  const entries = readdirSync(dir).sort();
  const table = entries.map((name) => {
    const bytes = readFileSync(join(dir, name));
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    return { name, base64: bytes.toString('base64'), sha256 };
  });
  return table;
}

const cmaps = collect('cmaps');
const standardFonts = collect('standard_fonts');

const tableBody = (rows) =>
  rows.map((row) => `  { name: ${JSON.stringify(row.name)}, base64: '${row.base64}', sha256: '${row.sha256}' }`).join(',\n');

const body = `/**
 * GENERATED by scripts/generate-asset-module.mjs from pdfjs-dist. Do not edit;
 * regenerate instead.
 */

export type PdfAsset = { name: string; base64: string; sha256: string };

export const PDF_CMAPS: PdfAsset[] = [
${tableBody(cmaps)}
];

export const PDF_STANDARD_FONTS: PdfAsset[] = [
${tableBody(standardFonts)}
];
`;

writeFileSync(resolve('src/pdf/generated/pdfAssets.ts'), body);
console.log(`cmaps: ${cmaps.length}, standard fonts: ${standardFonts.length}`);
